/**
 * Returns a translated term for a given English text and target language code.
 */
export function translateUiTerm(text: string, locale: LanguageCode): string {
  if (locale === "en" || !text) return text;
  const match = UI_TRANSLATIONS[text];
  if (match && match[locale]) {
    return match[locale]!;
  }
  return text;
}

/**
 * Universally resolves copy objects for any of India's 25 supported languages.
 * Falls back safely to 'en' when specific key translations are absent.
 */
export function getCopyLabels<T extends Record<string, unknown>>(
  copyObj: Record<string, T>,
  locale: LanguageCode | string,
): T {
  const loc = (locale as LanguageCode) || "en";
  if (copyObj[loc]) {
    return copyObj[loc];
  }
  const baseCopy = copyObj.en ?? copyObj[Object.keys(copyObj)[0]];
  if (!baseCopy) return {} as T;

  // If no explicit translation object exists for loc, dynamically map translated UI terms
  const result: Record<string, unknown> = { ...baseCopy };
  for (const [key, val] of Object.entries(baseCopy)) {
    if (typeof val === "string") {
      result[key] = translateUiTerm(val, loc as LanguageCode);
    }
  }

  return result as T;
}
